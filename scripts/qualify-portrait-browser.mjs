// Live browser proof of the portrait panel in the continuous world (real model, real ledger).
//   node scripts/qualify-portrait-browser.mjs [--base http://127.0.0.1:3081]
// Screenshots and observations: .local-library/portrait-eval/browser/
import { chromium } from "@playwright/test";
import { mkdir, writeFile } from "node:fs/promises";

const i = process.argv.indexOf("--base"), base = i > 0 ? process.argv[i + 1] : "http://127.0.0.1:3081";
const out = ".local-library/portrait-eval/browser", steps = [];
await mkdir(out, { recursive: true });
const browser = await chromium.launch({ channel: "chrome", headless: true });
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
const errors = []; page.on("pageerror", e => errors.push(String(e).slice(0, 200)));
const step = async (name, pass, detail = {}) => { steps.push({ name, pass, ...detail }); console.log(`${pass ? "pass" : "FAIL"} ${name} ${JSON.stringify(detail).slice(0, 260)}`); await page.screenshot({ path: `${out}/${steps.length.toString().padStart(2, "0")}-${name.replace(/\W+/g, "-")}.png` }); };
try {
  await page.emulateMedia({ reducedMotion: "reduce" });
  await page.goto(base + "/admin/library/preview#entry");
  await page.locator(".tw[data-ready]").waitFor({ timeout: 180000 });
  await page.getByRole("button", { name: "Ask Judge Overton", exact: true }).click();
  const panel = page.getByRole("complementary", { name: "Ask Judge Overton" });
  await panel.getByText(/Live replies · openai\/gpt-6-luna/).waitFor({ timeout: 30000 });
  await step("panel states live capability truthfully", true, { label: await panel.locator(".portrait-meta").first().textContent() });
  async function ask(question) {
    const before = await panel.locator(".portrait-answer").textContent().catch(() => null);
    const t0 = Date.now();
    await panel.getByLabel("Your question").fill(question);
    await panel.getByRole("button", { name: "Ask", exact: true }).click();
    await panel.getByRole("status").filter({ hasText: "Reading the evidence" }).waitFor({ timeout: 10000 }).catch(() => {});
    await page.waitForFunction(prev => { const a = document.querySelector(".portrait-answer"), s = document.querySelector(".portrait-status"); return a && a.textContent !== prev && !/Reading the evidence/.test(s?.textContent ?? ""); }, before, { timeout: 60000 });
    const ms = Date.now() - t0;
    return { ms, text: (await panel.locator(".portrait-answer").innerText()).replace(/^The portrait replies\s*/, ""), meta: await panel.locator(".portrait-meta").nth(1).textContent().catch(() => ""), diagnostics: await panel.locator("details.portrait-meta p").textContent().catch(() => ""), status: await panel.getByRole("status").textContent() };
  }
  let a = await ask("Good afternoon. What is this place, and who are you?");
  await step("open-ended question gets a generated reply", /Generated by openai\/gpt-6-luna/.test(a.meta) && /portrait|Overton|library/i.test(a.text), a);
  a = await ask("Which of John's books would you suggest to an engineer?");
  await step("follow-up question", /Generated by/.test(a.meta) && a.text.length > 40, a);
  a = await ask("How does Knowledge Services check its sources?");
  const inspect = panel.getByRole("button", { name: /^Inspect \d+ sources?$/ });
  await inspect.click();
  const sources = panel.getByRole("region", { name: "Verified sources" });
  await sources.waitFor({ timeout: 20000 });
  const titles = await sources.locator("summary").allTextContents();
  await step("sourced project answer with inspectable sources", /Generated by/.test(a.meta) && titles.some(t => /Knowledge Services/.test(t)), { ...a, sources: titles.filter(t => t !== "Source record") });
  // A visitor may ask three questions a minute; wait out the window as a visitor would.
  await page.waitForTimeout(61000);
  const hashBefore = new URL(page.url()).hash;
  a = await ask("Show me Mission Control");
  await panel.getByRole("status").filter({ hasText: /Opened|unavailable|cancelled/ }).waitFor({ timeout: 60000 });
  const opened = await panel.getByRole("status").textContent(), hashAfter = new URL(page.url()).hash;
  await step("explicit show request opens the book through signed navigation", /^Opened /.test(opened ?? "") && /mission/i.test(hashAfter), { ...a, status: opened, hashBefore, hashAfter });
  await page.goBack();
  await page.waitForFunction(h => location.hash === h, hashBefore, { timeout: 30000 }).catch(() => {});
  await step("Back returns to the previous place", new URL(page.url()).hash === hashBefore, { hash: new URL(page.url()).hash });
  // Reopen the panel if Back closed it, then Stop a turn mid-answer.
  if (!(await panel.isVisible())) await page.getByRole("button", { name: "Ask Judge Overton", exact: true }).click();
  await panel.getByLabel("Your question").fill("Compare every project on the shelves in detail, one by one.");
  await panel.getByRole("button", { name: "Ask", exact: true }).click();
  await page.waitForTimeout(800);
  await panel.getByRole("button", { name: "Stop", exact: true }).click();
  const stopped = await panel.getByRole("status").textContent();
  await step("Stop ends the turn and keeps the reading place", /Stopped/.test(stopped ?? ""), { status: stopped, hash: new URL(page.url()).hash });
} catch (error) { await step("unexpected failure", false, { error: String(error).slice(0, 400) }); }
finally {
  await writeFile(`${out}/observations.json`, JSON.stringify({ base, at: new Date().toISOString(), steps, pageErrors: errors }, null, 1));
  console.log(`${steps.filter(s => s.pass).length}/${steps.length} passed · page errors: ${errors.length}`);
  await browser.close();
}
