import { readFileSync, writeFileSync } from "node:fs";

// Documentation only: no database connection and no migration execution.
const root = new URL("../", import.meta.url);
const schema = readFileSync(new URL("prisma/schema.prisma", root), "utf8");
const modelNames = new Set([...schema.matchAll(/^model\s+(\w+)/gm)].map((m) => m[1]));
const blocks = [];
let pending = [];
let block;
for (const raw of schema.split(/\r?\n/)) {
  const line = raw.trim();
  if (line.startsWith("///")) {
    pending.push(line.slice(3).trim());
    continue;
  }
  const open = line.match(/^(model|enum)\s+(\w+)\s*\{/);
  if (open) {
    block = { kind: open[1], name: open[2], table: open[2], docs: pending.join(" "), fields: [], relations: [], rules: [], values: [] };
  } else if (block && line.startsWith("}")) {
    blocks.push(block);
    block = undefined;
  } else if (block) {
    const map = line.match(/^@@map\("([^"]+)"\)/);
    if (map) block.table = map[1];
    else if (line.startsWith("@@")) block.rules.push(line);
    else if (block.kind === "enum" && /^\w+$/.test(line)) block.values.push(line);
    else if (block.kind === "model") {
      const field = line.match(/^(\w+)\s+(\w+)(\[\]|\?)?\s*(.*)$/);
      if (field) {
        const [, name, type, suffix = "", attributes] = field;
        if (modelNames.has(type)) {
          if (attributes.includes("@relation(")) {
            block.relations.push({ name, type: type + suffix, attributes });
          }
        } else {
          block.fields.push({
            name,
            column: attributes.match(/@map\("([^"]+)"\)/)?.[1] ?? name,
            type: type + suffix,
            attributes: attributes.replace(/\s*@map\("[^"]+"\)/, "").trim(),
            docs: pending.join(" "),
          });
        }
      }
    }
  }
  pending = [];
}
const models = blocks.filter((b) => b.kind === "model");
const enums = blocks.filter((b) => b.kind === "enum");
const cell = (value) => value.replaceAll("|", "\\|").replaceAll("\n", " ");
const out = [
  '# New portfolio schema reference',
  '',
  'Generated from `prisma/schema.prisma` by `node scripts/gen-schema-reference.mjs`. Do not edit this file directly.',
  '',
  `The Library design contains **${models.length} application tables**, **${models.reduce((n, m) => n + m.fields.length, 0)} scalar columns**, and **${enums.length} enum types**. This reference documents the designed schema; it does not claim migrations have run on a live database. See [MIGRATION_STATUS.md](MIGRATION_STATUS.md) for verification status and [DATA_MODEL.md](DATA_MODEL.md) for the design.`,
  '',
  'Types are Prisma types. `?` means nullable, `[]` means an array; `@db.*` records the PostgreSQL native type. UUID primary keys use the Prisma `uuid()` default, which is not a database-side SQL default. Relations list the owning foreign-key field and delete behavior. `@@map` / `@map` define the SQL table/column names.',
  '',
  '## Table index',
  '',
  ...models.map((m) => `- [${m.table}](#${m.table.replaceAll('_', '-')}) (${m.name})`),
  '',
];
for (const model of models) {
  out.push(`## ${model.table.replaceAll('_', ' ')}`, '', `SQL table: \`${model.table}\`. Prisma model: \`${model.name}\`.`, '', model.docs || 'See the column and relation definitions below.', '', '| SQL column | Prisma field | Type | Constraints / defaults | Description |', '| --- | --- | --- | --- | --- |');
  for (const field of model.fields) {
    out.push(`| ${cell(field.column)} | ${cell(field.name)} | ${cell(field.type)} | ${cell(field.attributes)} | ${cell(field.docs)} |`);
  }
  if (model.relations.length) {
    out.push('', 'Foreign-key relations:', '', ...model.relations.map((r) => `- \`${r.name}: ${r.type}\` ${r.attributes}`));
  }
  if (model.rules.length) out.push('', 'Composite keys and indexes:', '', ...model.rules.map((r) => `- \`${r}\``));
  out.push('');
}
out.push('## Enum types', '');
for (const item of enums) out.push(`### ${item.table}`, '', `${item.docs ? item.docs + ' ' : ''}Values: ${item.values.map((v) => '`' + v + '`').join(', ')}.`, '');
writeFileSync(new URL('docs/SCHEMA_REFERENCE.md', root), out.join('\n'), 'utf8');
console.log(`Documented ${models.length} tables, ${models.reduce((n, m) => n + m.fields.length, 0)} columns, and ${enums.length} enums.`);
