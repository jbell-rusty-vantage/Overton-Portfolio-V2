#!/usr/bin/env node
// Turns `///` doc comments in prisma/schema.prisma into Postgres COMMENT ON
// statements, so every table/column/enum explains itself inside the Neon
// console and to agents using the Neon MCP `describe_table_schema` tool.
//
// Usage: node scripts/gen-comments.mjs > prisma/migrations/<new>/comments.sql
// (then paste/append into a migration). Re-run whenever doc comments change;
// COMMENT ON is idempotent.
import { readFileSync } from "node:fs";

const src = readFileSync(new URL("../prisma/schema.prisma", import.meta.url), "utf8");
const lines = src.split("\n");

const q = (s) => `'${s.replace(/'/g, "''")}'`;
const modelNames = new Set([...src.matchAll(/^model\s+(\w+)/gm)].map((m) => m[1]));

const out = ["-- Generated by scripts/gen-comments.mjs from /// doc comments in schema.prisma"];
let pending = [];
let block = null; // { kind: 'model'|'enum', name, table, docs, fields: [] }

for (const raw of lines) {
  const line = raw.trim();
  if (line.startsWith("///")) {
    pending.push(line.slice(3).trim());
    continue;
  }
  const open = line.match(/^(model|enum)\s+(\w+)\s*\{/);
  if (open) {
    block = { kind: open[1], name: open[2], table: open[2], docs: pending.join(" "), fields: [] };
    pending = [];
    continue;
  }
  if (block && line.startsWith("}")) {
    if (block.kind === "model") {
      if (block.docs) out.push(`COMMENT ON TABLE "${block.table}" IS ${q(block.docs)};`);
      for (const f of block.fields) out.push(`COMMENT ON COLUMN "${block.table}"."${f.column}" IS ${q(f.docs)};`);
    } else if (block.docs) {
      out.push(`COMMENT ON TYPE "${block.table}" IS ${q(block.docs)};`);
    }
    block = null;
    pending = [];
    continue;
  }
  if (!block) {
    pending = [];
    continue;
  }
  const map = line.match(/^@@map\("([^"]+)"\)/);
  if (map) {
    block.table = map[1];
    continue;
  }
  if (block.kind === "model") {
    const field = line.match(/^(\w+)\s+(\w+)(\[\]|\?)?/);
    if (field && pending.length) {
      const [, name, type] = field;
      const isRelation = modelNames.has(type);
      if (!isRelation) {
        const col = line.match(/@map\("([^"]+)"\)/);
        block.fields.push({ column: col ? col[1] : name, docs: pending.join(" ") });
      }
    }
  }
  pending = [];
}

process.stdout.write(out.join("\n") + "\n");
